-- Muninn v1.1: categories, triggers that fire, proactive tips.
-- Additive only (ALTER TABLE ADD COLUMN, new tables, new indexes), so it is safe on a live v1 database.

-- Triggers: what to create when they fire, and which occurrence they are on.
ALTER TABLE triggers ADD COLUMN kind TEXT;               -- 'warranty_end', 'birthday_0', 'debt_nudge', ...
ALTER TABLE triggers ADD COLUMN payload_enc TEXT;        -- encrypted JSON {title, person_id}; titles can hold names
ALTER TABLE triggers ADD COLUMN occurrence_date TEXT;    -- YYYY-MM-DD of the anchor occurrence next_fire_at belongs to
ALTER TABLE triggers ADD COLUMN last_occurrence TEXT;    -- YYYY-MM-DD of the occurrence it last fired for
ALTER TABLE triggers ADD COLUMN require_open INTEGER NOT NULL DEFAULT 0; -- skip and stop when the source item is closed
CREATE INDEX triggers_item ON triggers(item_id);
CREATE INDEX triggers_anchor ON triggers(anchor_type, anchor_id);

-- Items created by a trigger point back to it.
ALTER TABLE items ADD COLUMN source_trigger_id TEXT;
CREATE INDEX items_subtype ON items(subtype, status, created_at);

CREATE INDEX links_item ON links(item_id, target_type);
CREATE INDEX events_item ON events(item_id, type);

-- Proactive tips. Generated by rules (worker/core/tips.ts); the user's act / snooze / dismiss is kept,
-- so a dismissed tip never returns and rules that keep getting dismissed are muted.
CREATE TABLE tips (
  id TEXT PRIMARY KEY,
  rule TEXT NOT NULL,
  key TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL CHECK (status IN ('active', 'acted', 'dismissed', 'snoozed', 'expired')),
  score REAL NOT NULL,
  domain TEXT NOT NULL DEFAULT 'none',
  item_id TEXT,
  content_enc TEXT NOT NULL,    -- encrypted JSON {title, body, because[], keep[]}
  wording_enc TEXT,             -- optional model rewording, kept only if it passed the fact check
  expires_on TEXT,              -- YYYY-MM-DD local
  snoozed_until TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
) STRICT;
CREATE INDEX tips_status ON tips(status, score);
CREATE INDEX tips_rule ON tips(rule, status, updated_at);
